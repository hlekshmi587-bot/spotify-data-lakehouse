"""Run every compiled SQL in analyses/ against the dbt DuckDB warehouse and write
docs/sql_analytics_results.md (question, SQL and the real result table).

Usage (from the dbt project folder, after `dbt build` and `dbt compile`):
    python scripts/run_analyses.py
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path

import duckdb

ROOT = Path(__file__).resolve().parents[1]
DB = ROOT / "target" / "spotify_warehouse.duckdb"
COMPILED = ROOT / "target" / "compiled" / "spotify_dbt" / "analyses"
OUT = ROOT / "docs" / "sql_analytics_results.md"


def md_table(columns, rows) -> str:
    def fmt(v):
        if v is None:
            return ""
        if isinstance(v, float):
            return f"{v:,.4f}".rstrip("0").rstrip(".") if abs(v) < 1000 else f"{v:,.0f}"
        if isinstance(v, int):
            return f"{v:,}"
        return str(v).replace("|", "/")
    head = "| " + " | ".join(columns) + " |\n|" + "|".join("---" for _ in columns) + "|\n"
    return head + "\n".join("| " + " | ".join(fmt(v) for v in r) + " |" for r in rows)


def main() -> None:
    if not DB.exists() or not COMPILED.exists():
        raise SystemExit("Run `dbt build` and `dbt compile` first.")
    con = duckdb.connect(str(DB), read_only=True)
    parts = [
        "# SQL analytics - results\n",
        f"_Generated by `scripts/run_analyses.py` on {dt.datetime.now(dt.timezone.utc):%Y-%m-%d %H:%M} UTC "
        "from the dbt star schema. Source SQL: `analyses/`._\n",
        "> **Read the numbers with the data limits in mind** (see `README.md`): the chart file is a sample, "
        "~99.9% of Top 200 rows come from 7 dates, and audio features exist only for the ~17% of chart rows "
        "whose track is in `tracks.csv`. Seasonal/temporal results are indicative, not conclusions.\n",
    ]
    for f in sorted(COMPILED.glob("*.sql")):
        sql = f.read_text()
        question = sql.splitlines()[0].replace("-- Question:", "").strip()
        caveats = [l.replace("-- Caveat:", "").strip() for l in sql.splitlines() if l.startswith("-- Caveat:")]
        cur = con.execute(sql)
        cols = [d[0] for d in cur.description]
        rows = cur.fetchall()
        src = "\n".join(l for l in (ROOT / "analyses" / f.name).read_text().splitlines()
                        if not l.startswith(("-- Question:", "-- Caveat:")))
        parts.append(f"\n## {f.stem}\n**{question}**\n")
        for cv in caveats:
            parts.append(f"> **Caveat:** {cv}\n")
        parts.append("```sql\n" + src.strip() + "\n```\n")
        parts.append(md_table(cols, rows) + "\n")
        print(f"{f.name}: {len(rows)} rows")
    OUT.write_text("\n".join(parts), encoding="utf-8")
    print("written", OUT)


if __name__ == "__main__":
    main()
